export function generateBulletSuggestions(role: string): string[] {
  const key = role.toLowerCase().replace(/\s+/g, "-").replace(/[^a-z0-9-]/g, "");
  const matched = bulletSuggestions[key];
  if (matched) {
    return matched.map((s) => s.replace(/\[([^\]]*)\]/g, (_, p) => `[${p}]`));
  }
  // Fuzzy: find closest key
  const keys = Object.keys(bulletSuggestions);
  const fuzzy = keys.find((k) => key.includes(k.split("-")[0]) || k.includes(key.split("-")[0]));
  const fallback = fuzzy ? bulletSuggestions[fuzzy] : bulletSuggestions["software-engineer"];
  return fallback.map((s) => s.replace(/\[([^\]]*)\]/g, (_, p) => `[${p}]`));
}
